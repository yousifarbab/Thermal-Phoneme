# ============================================================
# 2. خريطة عكسية (للترددات إلى حروف)
# ============================================================
REVERSE_PHONEME_MAP = {freq: letter for letter, freq in PHONEME_MAP.items()}

# ============================================================
# 3. دوال مساعدة
# ============================================================
def get_frequency(letter: str) -> float:
    """
    تُعيد التردد المطابق للحرف المدخل.
    
    Args:
        letter (str): حرف عربي واحد.
    
    Returns:
        float: التردد بالـ MHz، أو 0.0 إذا لم يتم العثور على الحرف.
    
    Example:
        >>> get_frequency('ا')
        100.0
    """
    return PHONEME_MAP.get(letter, 0.0)

def get_letter(frequency: float) -> str:
    """
    تُعيد الحرف المطابق للتردد المدخل.
    
    Args:
        frequency (float): التردد بالـ MHz.
    
    Returns:
        str: الحرف العربي، أو سلسلة فارغة إذا لم يتم العثور على التردد.
    
    Example:
        >>> get_letter(105.0)
        'ب'
    """
    # نسمح بخطأ بسيط (± 0.5 MHz) لتجنب مشاكل الدقة
    tolerance = 0.5
    for letter, freq in PHONEME_MAP.items():
        if abs(freq - frequency) <= tolerance:
            return letter
    return ''

def get_all_letters() -> list:
    """
    تُعيد قائمة بجميع الحروف العربية في الخريطة.
    
    Returns:
        list: قائمة الحروف العربية.
    
    Example:
        >>> get_all_letters()
        ['أ', 'ب', 'ت', 'ث', ...]
    """
    return list(PHONEME_MAP.keys())

def get_all_frequencies() -> list:
    """
    تُعيد قائمة بجميع الترددات في الخريطة.
    
    Returns:
        list: قائمة الترددات بالـ MHz.
    
    Example:
        >>> get_all_frequencies()
        [100.0, 105.0, 110.0, ...]
    """
    return list(PHONEME_MAP.values())

def get_letter_count() -> int:
    """
    تُعيد عدد الحروف العربية في الخريطة.
    
    Returns:
        int: عدد الحروف (28 حرفاً).
    """
    return len(PHONEME_MAP)

